import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync('src/components/AddressAutocomplete.jsx', 'utf8');
const file = ts.createSourceFile('AddressAutocomplete.jsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JSX);
const buttons = [];
const visit = node => {
  if (ts.isJsxOpeningElement(node) && node.tagName.getText(file) === 'button') buttons.push(node);
  ts.forEachChild(node, visit);
};
visit(file);
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
check(buttons.length === 1, 'Suggestions use one real button template, not mouse-only list rows');
const attrs = new Map(buttons[0].attributes.properties.map(attribute => [attribute.name?.getText(file), attribute.initializer?.getText(file)]));
check(attrs.get('type') === '"button"', 'Selection cannot submit a checkout form');
check(attrs.get('onClick')?.includes('handleSelect(s)'), 'Native click/touch/keyboard activation selects the address');
check(attrs.get('onPointerDown')?.includes('preventDefault()'), 'Pointer activation preserves input focus to avoid iOS keyboard target movement');
check(attrs.get('onPointerUp')?.includes('handleSelect(s)'), 'WebKit touch selection does not depend on a compatibility click');
check(attrs.has('onPointerCancel') && attrs.get('onPointerMove')?.includes('Math.hypot'), 'Cancelled taps and scrolling cannot select an address');
check(!source.includes('onMouseDown'), 'No mouse-only selection dependency');
check(source.includes("document.addEventListener('pointerdown', handler)") && source.includes("document.removeEventListener('pointerdown', handler)"), 'Outside touch and cleanup use matching pointer listeners');
check(source.includes("if (e.key === 'Escape') dismissSuggestions()"), 'Keyboard dismissal supported');
check(source.includes('emit({ street: s.street, city: s.city, state: s.state, zip: s.zip })'), 'Selection preserves all four structured fields');
check(source.includes('if (request !== requestRef.current) return;'), 'Stale responses cannot replace current suggestions');
check(source.indexOf('clearTimeout(debounceRef.current);', source.indexOf('const fetchSuggestions')) < source.indexOf('normalizedQuery.length < 3'), 'Short queries cancel pending debounce too');
check(source.includes('dismissSuggestions();\n    emit('), 'Selection invalidates pending response before emitting');
check(source.includes('aria-controls={suggestionsId}') && source.includes('id={suggestionsId}'), 'Input identifies its suggestion list');
const browser = fs.readFileSync('scripts/tests/checkout-browser/address-touch-tests.mjs', 'utf8');
check(browser.includes('hasTouch: true') && browser.includes("['webkit', webkit]") && browser.includes('.tap()'), 'Separate real-browser regression covers touch in WebKit and Chromium');
console.log(JSON.stringify({ suite: 'g175-address-selection-contract', checks, passed: true, productionWrites: 0, providerCalls: 0 }));
